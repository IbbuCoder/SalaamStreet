/* SalaamStreet — build-ios-content.js
   The native iOS app (ios/) uses the same content as the website. This copies
   it out of the website's data files into JSON the app bundles, so there is
   one source of truth: edit js/duas.js, js/content.js, js/surahs.js,
   js/extras.js or js/core.js, then run

     node tools/build-ios-content.js

   and commit the result. tests/ios-content.test.js fails when the JSON is out
   of date. It also writes the prayer-time fixtures the Swift tests compare
   against (from js/praytimes.js, which tests/praytimes.test.js checks against
   the adhan library), so the app and the website calculate the same times. */
"use strict";
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.resolve(__dirname, "..");
const CORE = path.join(ROOT, "ios", "SalaamStreetCore");
const OUT_CONTENT = path.join(CORE, "Sources", "SalaamStreetCore", "Resources", "content.json");
const OUT_FIXTURES = path.join(CORE, "Tests", "SalaamStreetCoreTests", "Fixtures", "praytimes.json");

function load() {
  const box = { console, localStorage: { getItem: () => null, setItem() {}, removeItem() {}, key: () => null, length: 0 } };
  box.window = box;
  box.navigator = { languages: ["en-US"] };
  box.document = { getElementById: () => null };
  vm.createContext(box);
  for (const f of ["js/surahs.js", "js/duas.js", "js/extras.js", "js/content.js", "js/praytimes.js", "js/core.js"]) {
    vm.runInContext(fs.readFileSync(path.join(ROOT, f), "utf8"), box, { filename: f });
  }
  return box.SS;
}

function content(SS) {
  return {
    note: "Generated by tools/build-ios-content.js from the website's data files. Do not edit by hand.",
    surahs: SS.SURAHS.map((s) => ({ number: s.n, arabicName: s.ar, englishName: s.en, meaning: s.meaning, ayahCount: s.ayahs, revelation: s.type })),
    juz: SS.JUZ.map((j, i) => ({ number: i + 1, surah: j[0], ayah: j[1] })),
    translations: SS.TRANSLATIONS.map((t) => ({ id: t.id, label: t.label, language: t.lang, rightToLeft: t.dir === "rtl" })),
    reciters: SS.RECITERS.map((r) => ({ id: r.id, englishName: r.en, arabicName: r.ar })),
    calculationMethods: SS.CALC_METHODS.map((m) => ({ id: m.id, englishName: m.en, arabicName: m.ar })),
    duaCategories: SS.DUA_CATEGORIES.map((c) => ({ id: c.id, symbol: c.icon, englishName: c.en, arabicName: c.ar })),
    duas: SS.DUAS.map((d) => ({
      id: d.id, category: d.category, title: d.titleEn, arabic: d.arabic,
      transliteration: d.transliteration || "", translation: d.translationEn || "", source: d.source,
    })),
    dhikrPresets: SS.DHIKR_PRESETS.map((d) => ({ id: d.id, arabic: d.ar, title: d.en, meaning: d.meaning, target: d.target, source: d.source })),
    namesOfAllah: SS.NAMES.map((n) => ({ number: n.n, arabic: n.ar, transliteration: n.tr, meaning: n.en })),
    hadithCollections: SS.HADITH_COLLECTIONS.map((c) => ({
      id: c.id, group: c.group, englishName: c.en, arabicName: c.ar, englishEdition: c.eng, arabicEdition: c.ara,
      complete: !!c.bounded, lastNumber: c.last, mixedGrades: !!c.mixed, citation: c.cite,
    })),
    islamicEvents: SS.ISLAMIC_EVENTS.map((e) => ({ month: e.month, day: e.day, englishName: e.en, arabicName: e.ar, note: e.note })),
    sources: {
      alquran: SS.ALQURAN, aladhan: SS.ALADHAN, audio: SS.AUDIO_URL, audioBitrates: SS.AUDIO_BITRATES,
      tafsirMirrors: SS.TAFSIR_MIRRORS, tafsirEdition: SS.TAFSIR_EDITION, hadith: SS.HADITH_BASE,
    },
  };
}

/* Prayer-time fixtures: cities across latitudes and hemispheres, four seasons,
   every method and both Asr schools, at fixed UTC offsets. */
function fixtures(SS) {
  const cities = [
    { name: "Makkah", lat: 21.42, lng: 39.83, tz: 180 },
    { name: "Chicago", lat: 41.88, lng: -87.63, tz: -300 },
    { name: "London", lat: 51.51, lng: -0.13, tz: 60 },
    { name: "Jakarta", lat: -6.21, lng: 106.85, tz: 420 },
    { name: "Cape Town", lat: -33.92, lng: 18.42, tz: 120 },
    { name: "Oslo", lat: 59.91, lng: 10.75, tz: 120 },
    { name: "Karachi", lat: 24.86, lng: 67.01, tz: 300 },
  ];
  const dates = [[2026, 3, 20], [2026, 6, 21], [2026, 9, 23], [2026, 12, 21]];
  const out = [];
  for (const c of cities) for (const [y, m, d] of dates) for (const method of Object.keys(SS.praytimes.METHODS).map(Number)) for (const school of [0, 1]) {
    const times = SS.praytimes.times(new Date(y, m - 1, d), c.lat, c.lng, { method, school, tzOffset: c.tz });
    out.push({ city: c.name, lat: c.lat, lng: c.lng, tzOffsetMinutes: c.tz, year: y, month: m, day: d, method, school,
      fajr: times.Fajr, sunrise: times.Sunrise, dhuhr: times.Dhuhr, asr: times.Asr, maghrib: times.Maghrib, isha: times.Isha });
  }
  return out;
}

function build() {
  const SS = load();
  return {
    [OUT_CONTENT]: JSON.stringify(content(SS), null, 1) + "\n",
    [OUT_FIXTURES]: JSON.stringify(fixtures(SS), null, 1) + "\n",
  };
}

if (require.main === module) {
  const files = build();
  for (const [file, text] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
    console.log("wrote " + path.relative(ROOT, file) + " (" + Math.round(text.length / 1024) + " KB)");
  }
}
module.exports = { build };
