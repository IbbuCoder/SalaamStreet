#!/usr/bin/env node
/* SalaamStreet — hadith book index generator.
 *
 * The browse-by-number collections (Bukhari, Muslim, the Sunan, Muwatta) are
 * split into books (kitab). hadith-api lists each book's name, and every
 * hadith's book, in info.json (~10 MB) — far too big to load in the app — so
 * this script keeps just each book's name and where it starts in
 * js/hadith-books.js. A book starts at its hadith referenced as "Book n,
 * Hadith 1" (the published first/last numbers include a few stray entries
 * that would jump to the wrong place). The app loads that file only when someone opens one of
 * these collections.
 *
 *   node tools/build-hadith-books.js            # downloads info.json
 *   node tools/build-hadith-books.js info.json  # or uses a local copy
 */
"use strict";
const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const ROOT = path.resolve(__dirname, "..");
const SRC = "https://raw.githubusercontent.com/fawazahmed0/hadith-api/1/info.json";
const COLLECTIONS = ["bukhari", "muslim", "abudawud", "tirmidhi", "nasai", "ibnmajah", "malik"];

const local = process.argv[2];
const info = JSON.parse(local ? fs.readFileSync(local, "utf8") : execFileSync("curl", ["-sSfL", "-m", "120", SRC], { maxBuffer: 64 << 20 }).toString());

const out = {};
for (const id of COLLECTIONS) {
  const meta = info[id].metadata;
  const best = {}; // book → its hadith with the lowest in-book number (ideally "Book n, Hadith 1")
  for (const h of info[id].hadiths) {
    const r = h.reference;
    if (!r || r.book == null || !(r.hadith >= 1)) continue; // entries numbered 0 are stray placeholders
    const cur = best[r.book];
    if (!cur || r.hadith < cur.hadith || (r.hadith === cur.hadith && h.hadithnumber < cur.n)) best[r.book] = { hadith: r.hadith, n: Math.floor(h.hadithnumber) };
  }
  const books = [];
  for (const [n, name] of Object.entries(meta.sections)) {
    if (!name || !best[n]) continue; // section 0 is an empty placeholder in most books
    books.push([+n, name.replace(/\s+/g, " ").trim(), best[n].n]);
  }
  books.sort((a, b) => a[0] - b[0]);
  out[id] = books;
}

const body = "/* SalaamStreet — hadith books: [book number, name, first hadith].\n" +
  "   Generated by tools/build-hadith-books.js from hadith-api (fawazahmed0) — do not edit by hand. */\n" +
  "window.SS = window.SS || {};\nSS.HADITH_BOOKS = {\n" +
  Object.entries(out).map(([id, books]) => "  " + id + ": [\n" + books.map((b) => "    " + JSON.stringify(b) + ",").join("\n") + "\n  ],").join("\n") +
  "\n};\n";
fs.writeFileSync(path.join(ROOT, "js/hadith-books.js"), body);
for (const [id, books] of Object.entries(out)) console.log(id.padEnd(9), books.length, "books");
