/* The iOS app bundles the website's content (duas, dhikr, surahs, names,
   hadith collections, translations, reciters, methods) as JSON generated by
   tools/build-ios-content.js, and its prayer-time tests compare against
   fixtures from js/praytimes.js. This fails when either is out of date.
   Fix: node tools/build-ios-content.js
   Run: node --test tests/ios-content.test.js */
"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("fs");
const { build } = require("../tools/build-ios-content.js");

test("ios content.json and prayer-time fixtures match the website's data files", () => {
  for (const [file, text] of Object.entries(build())) {
    assert.ok(fs.existsSync(file), "missing " + file + " — run node tools/build-ios-content.js");
    assert.equal(fs.readFileSync(file, "utf8"), text, file + " is out of date — run node tools/build-ios-content.js");
  }
});

test("the iOS app version matches the beta being shipped", () => {
  const pbx = fs.readFileSync(require("path").join(__dirname, "..", "ios/SalaamStreet.xcodeproj/project.pbxproj"), "utf8");
  const versions = [...new Set([...pbx.matchAll(/MARKETING_VERSION = ([^;]+);/g)].map((m) => m[1]))];
  const builds = [...new Set([...pbx.matchAll(/CURRENT_PROJECT_VERSION = ([^;]+);/g)].map((m) => m[1]))];
  assert.deepEqual(versions, ["3.0.0"]);
  assert.deepEqual(builds, ["1"]);
  assert.match(require("../package.json").version, /^3\.0\.0-beta/);
});
